#!/usr/bin/env python3
"""Generates every Ledger MRU icon from one drawing (v1.1 open-book icon).

The book is drawn once, as stroke centre lines in the 1254 px grid of the
reference image (reference.png). Everything else is derived:

  ledger-mru-foreground.svg   adaptive-icon foreground, 108 grid
  ledger-mru.svg              full icon (rounded square), desktop + legacy Android
  ledger-mru.png              the same, 256 px
  --android <res dir>         drawable/ic_launcher_foreground.xml + mipmap-*/ic_launcher.png
  --png <file>                one more 256 px copy (the Slint window icon)

    python3 branding/make_icons.py [--android android/app/src/main/res] [--png <file>]

Needs `resvg` on PATH.
"""
import argparse
import re
import subprocess
from pathlib import Path

BRAND = Path(__file__).resolve().parent

BG = "#C67139"     # terracotta, = ic_launcher_background and the app accent
FG = "#F5EAD8"     # cream, = app background

# ── The drawing (source pixels, centre lines) ────────────────────────────────
LEFT_PAGE = ("M627 425 C627 405 618 392 600 380 C555 343 485 325 405 325 "
             "C345 325 285 338 238 355 C218 362 206 377 206 398 L206 838 "
             "C206 855 218 864 234 858 C285 838 345 825 405 825 "
             "C480 825 555 845 605 880 C613 887 620 893 627 893 Z")
SPINE = "M627 425 L627 893"
TEXT_LINES = [(311, 521, y) for y in (488, 602, 715)]
OUTLINE_W, LINE_W = 50, 41
MIRROR = 1254                    # right page: x' = MIRROR - x (symmetric about the spine)
CX, CY = 627, 609.5              # centre of the book's bounding box

NUM = re.compile(r"[A-Za-z]|-?\d+(?:\.\d+)?")


def map_xy(d, fx, fy=lambda y: y):
    """Applies fx to every x and fy to every y of an absolute M/L/C path."""
    out, i = [], 0
    for t in NUM.findall(d):
        if t.isalpha():
            out.append(t)
            i = 0
        else:
            v = float(t)
            out.append(f"{(fx(v) if i % 2 == 0 else fy(v)):.2f}".rstrip("0").rstrip("."))
            i += 1
    return " ".join(out)


def outline():
    return " ".join([LEFT_PAGE, map_xy(LEFT_PAGE, lambda x: MIRROR - x), SPINE])


def lines():
    parts = []
    for a, b, y in TEXT_LINES:
        parts += [f"M{a} {y} L{b} {y}", f"M{MIRROR - b} {y} L{MIRROR - a} {y}"]
    return " ".join(parts)


def place(d, scale, cx, cy):
    """Scales the drawing by `scale` and centres it on (cx, cy)."""
    return map_xy(d, lambda x: cx + (x - CX) * scale, lambda y: cy + (y - CY) * scale)


def svg_strokes(scale, cx, cy):
    return (f'<g fill="none" stroke="{FG}" stroke-linecap="round" stroke-linejoin="round">'
            f'<path stroke-width="{OUTLINE_W * scale:.2f}" d="{place(outline(), scale, cx, cy)}"/>'
            f'<path stroke-width="{LINE_W * scale:.2f}" d="{place(lines(), scale, cx, cy)}"/></g>')


# Adaptive icon: 108 grid, the book stays inside the 66-wide safe circle
# (farthest corner ≈ 30 units from the centre, limit 33).
ADAPTIVE_SCALE = 0.058
# Full icon: rounded square on a 256 grid, book ≈ 60 % of the width.
FULL_SCALE = 0.172


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path)


def render(svg, png, size):
    png.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["resvg", "-w", str(size), "-h", str(size), str(svg), str(png)], check=True)
    print("wrote", png, f"({size}px)")


def main():
    args = argparse.ArgumentParser()
    args.add_argument("--android", type=Path)
    args.add_argument("--png", type=Path)
    args = args.parse_args()
    fg_svg = BRAND / "ledger-mru-foreground.svg"
    write(fg_svg, '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">'
          + svg_strokes(ADAPTIVE_SCALE, 54, 54) + "</svg>\n")

    full_svg = BRAND / "ledger-mru.svg"
    write(full_svg, '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">'
          f'<rect x="8" y="8" width="240" height="240" rx="54" fill="{BG}"/>'
          + svg_strokes(FULL_SCALE, 128, 128) + "</svg>\n")

    render(full_svg, BRAND / "ledger-mru.png", 256)
    if args.png:
        render(full_svg, args.png, 256)
    if args.android:
        s = ADAPTIVE_SCALE
        path_xml = lambda w, d: (
            f'    <path android:strokeColor="{FG}" android:strokeWidth="{w * s:.2f}"\n'
            '        android:strokeLineCap="round" android:strokeLineJoin="round"\n'
            f'        android:pathData="{place(d, s, 54, 54)}" />\n')
        write(args.android / "drawable/ic_launcher_foreground.xml",
              '<?xml version="1.0" encoding="utf-8"?>\n'
              "<!-- Generated by branding/make_icons.py: open book (v1.1), cream on the\n"
              "     terracotta background, inside the adaptive-icon safe zone. -->\n"
              '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
              '    android:width="108dp" android:height="108dp"\n'
              '    android:viewportWidth="108" android:viewportHeight="108">\n'
              + path_xml(OUTLINE_W, outline()) + path_xml(LINE_W, lines()) + "</vector>\n")

        for folder, size in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
            render(full_svg, args.android / f"mipmap-{folder}/ic_launcher.png", size)


if __name__ == "__main__":
    main()
