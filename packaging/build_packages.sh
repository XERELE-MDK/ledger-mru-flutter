#!/usr/bin/env bash
# Builds the Linux packages of Ledger MRU (Flutter, Linux) into dist/:
#   *.pkg.tar.zst  Arch, Manjaro…              sudo pacman -U <file>      (if makepkg is installed)
#   *.deb          Debian 12+, Ubuntu 22.04+   sudo apt install ./<file>
#   *.rpm          Fedora 35+, openSUSE…       sudo dnf install ./<file>  (if rpmbuild is installed)
#   *.tar.gz       any distribution, no root   tar xf <file> && <folder>/install.sh
#
# Usage: packaging/build_packages.sh [--no-build]
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
root=$(dirname "$here")
dist=$root/dist
stage=$root/build/package-stage
rel=1   # package release: bump to repackage the same version
maint="XERELE-MDK <137554322+XERELE-MDK@users.noreply.github.com>"
say() { printf '\n\033[1m== %s\033[0m\n' "$*"; }
build=1; [[ ${1:-} == --no-build ]] && build=0

pkg=ledger-mru-flutter
desc="Personal double-entry ledger in ouguiya (MRU), Flutter build of the phone app"
url=https://github.com/XERELE-MDK/ledger-mru-flutter
ver=$(grep -m1 '^version:' "$root/pubspec.yaml" | sed 's/version: *//; s/+.*//')
bundle=$root/build/linux/x64/release/bundle
arch_dep="glibc gcc-libs gtk3"
arch_opt="'zenity: Export / Import dialogs' 'xdg-user-dirs: open dialogs in Downloads'"
deb_dep="libc6 (>= @GLIBC@), libstdc++6, libgtk-3-0t64 | libgtk-3-0, libepoxy0"
deb_rec="zenity, xdg-user-dirs"
rpm_rec="zenity xdg-user-dirs"

if (( build )); then
  say "Flutter Linux release build"
  (cd "$root" && flutter build linux --release)
fi
[[ -x $bundle/ledger_mru ]] || { echo "missing: $bundle/ledger_mru" >&2; exit 1; }
binaries=("$bundle/ledger_mru" "$bundle"/lib/*.so)

stage_tree() {
  mkdir -p "$s/opt" "$s/usr/bin"
  cp -a "$bundle" "$s/opt/$pkg"      # the bundle finds lib/ and data/ next to itself
  ln -s "../../opt/$pkg/ledger_mru" "$s/usr/bin/$pkg"
  install -Dm644 "$here/app.mru.ledger_mru.desktop" "$s/usr/share/applications/app.mru.ledger_mru.desktop"
  install -Dm644 "$root/branding/ledger-mru.svg" "$s/usr/share/icons/hicolor/scalable/apps/app.mru.ledger_mru.svg"
  install -Dm644 "$root/branding/ledger-mru.png" "$s/usr/share/icons/hicolor/256x256/apps/app.mru.ledger_mru.png"
  install -Dm644 "$root/LICENSE" "$s/usr/share/licenses/$pkg/LICENSE"
}

# Each package is first laid out as it will be installed; every format wraps that same tree.
glibc_floor() { objdump -T "$@" 2>/dev/null | grep -o 'GLIBC_[0-9.]*' | sed 's/GLIBC_//' | sort -uV | tail -1; }
glibc=$(glibc_floor "${binaries[@]}")
rm -rf "$stage" "$dist"; mkdir -p "$stage" "$dist"
s=$stage/root
say "Staging $pkg $ver (needs glibc ≥ $glibc)"
stage_tree

# ---- Arch (.pkg.tar.zst)
if command -v makepkg >/dev/null; then
  say "Arch package"
  b=$stage/arch; mkdir -p "$b"
  cat > "$b/PKGBUILD" <<EOF
# Generated by packaging/build_packages.sh — repackages the release build.
pkgname=$pkg
pkgver=$ver
pkgrel=$rel
pkgdesc="$desc"
arch=('x86_64')
url="$url"
license=('GPL-3.0-or-later')
depends=($arch_dep)
optdepends=($arch_opt)
options=('!strip' '!debug')
package() { cp -a "$s/." "\$pkgdir/"; }
EOF
  (cd "$b" && PKGDEST=$dist PACKAGER="$maint" makepkg -f --nodeps --noconfirm >/dev/null)
else
  say "Arch package skipped (makepkg missing)"
fi

# ---- Debian (.deb)
if command -v dpkg-deb >/dev/null; then
  say "Debian package"
  d=$stage/deb; mkdir -p "$d"; cp -a "$s/." "$d/"; mkdir -p "$d/DEBIAN"
  cat > "$d/DEBIAN/control" <<EOF
Package: $pkg
Version: $ver-$rel
Architecture: amd64
Maintainer: $maint
Homepage: $url
Installed-Size: $(du -sk --exclude=DEBIAN "$d" | cut -f1)
Depends: ${deb_dep//@GLIBC@/$glibc}
Recommends: $deb_rec
Section: misc
Priority: optional
Description: $desc
 Accounts, journal, ledger, monthly report and budgets, in ouguiya (MRU).
 Same JSON file format as the Android app; folder sync with Syncthing.
EOF
  dpkg-deb --root-owner-group -Zxz --build "$d" "$dist/${pkg}_${ver}-${rel}_amd64.deb" >/dev/null
fi

# ---- RPM (.rpm)
if command -v rpmbuild >/dev/null; then
  say "RPM package"
  r=$stage/rpm; mkdir -p "$r"
  files=$(cd "$s" && find usr -type f -o -type l | sed 's|^|/|')
  [[ -d $s/opt ]] && files+=$'\n'/opt/$pkg
  cat > "$r/$pkg.spec" <<EOF
Name:      $pkg
Version:   $ver
Release:   $rel
Summary:   $desc
License:   GPL-3.0-or-later
URL:       $url
BuildArch: x86_64
Requires:  libxkbcommon.so.0()(64bit)
Recommends: $rpm_rec
%global __os_install_post %{nil}
%global debug_package %{nil}
%global _build_id_links none
%description
Accounts, journal, ledger, monthly report and budgets, in ouguiya (MRU).
Same JSON file format as the Android app; folder sync with Syncthing.
%install
mkdir -p %{buildroot}
cp -a $s/. %{buildroot}/
%files
$files
EOF
  # _dbpath: Arch has no system RPM database; a private empty one avoids a scary error.
  rpmbuild -bb --quiet --define "_topdir $r" --define "_rpmdir $dist" --define "_dbpath $r/db" \
    --define "_build_name_fmt %%{NAME}-%%{VERSION}-%%{RELEASE}.%%{ARCH}.rpm" "$r/$pkg.spec"
fi

# ---- any distribution, no root (.tar.gz)
say "Portable archive"
t=$stage/$pkg-$ver-x86_64; mkdir -p "$t"; cp -a "$s/." "$t/"
install -m755 "$here/user-install.sh" "$t/install.sh"
tar -C "$stage" --owner=0 --group=0 -czf "$dist/$pkg-$ver-x86_64.tar.gz" "$pkg-$ver-x86_64"

rm -rf "$stage"
(cd "$dist" && sha256sum -- * > SHA256SUMS)
say "Done: $dist"; ls -lh "$dist"
